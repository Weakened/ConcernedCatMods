"""Turn AnimationSources/ladder_gait.json into Domain/Animation/GeneratedGait.cs (the values the game uses).

    python tools/animation/gait/compile_gait.py           # write the C#
    python tools/animation/gait/compile_gait.py --check   # exit 1 if the C# does not match the JSON
"""
import hashlib
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
JSON = os.path.join(ROOT, 'src', 'ConcernedLadders', 'AnimationSources', 'ladder_gait.json')
OUT = os.path.join(ROOT, 'src', 'ConcernedLadders', 'Domain', 'Animation', 'GeneratedGait.cs')


def f(value):
    text = ('%.6f' % value).rstrip('0').rstrip('.')
    if text in ('-0', ''):
        text = '0'
    return text + 'f'


def arr(values):
    return '{ ' + ', '.join(f(v) for v in values) + ' }'


def render(data, json_hash):
    body, hints = data['body'], data['hints']
    lines = [
        '// <auto-generated> by tools/animation/gait/compile_gait.py from AnimationSources/ladder_gait.json,',
        '// which export_gait.py wrote from AnimationSources/LadderGait.blend. Edit the .blend, never this file.',
        '// </auto-generated>',
        'namespace TheConcernedCat.ConcernedLadders.Domain.Animation;',
        '',
        'internal static class GeneratedGait',
        '{',
        '    internal const string BlendSha256 = "%s";' % data['sourceSha256'],
        '    internal const string JsonSha256 = "%s";' % json_hash,
        '    internal const string Blender = "%s";' % data['blender'],
        '',
        '    internal static GaitShape Shape() => new GaitShape',
        '    {',
        '        StrideRungs = %d,' % data['strideRungs'],
        '        Start = new[] %s,' % arr(data['start']),
        '        Length = new[] %s,' % arr(data['length']),
        '        FootLowRel = %s,' % f(data['footLowRel']),
        '        HandMidFromShoulder = %s,' % f(data['handMidFromShoulder']),
        '        DwellSlow = %s,' % f(data['dwellSlow']),
        '        SwingCurve = new[] %s,' % arr(data['swing']),
        '        ArcOut = new[] { new[] %s, new[] %s },' % (arr(data['arcOut'][0]), arr(data['arcOut'][1])),
        '        ArcUp = new[] { new[] %s, new[] %s },' % (arr(data['arcUp'][0]), arr(data['arcUp'][1])),
        '    };',
        '',
    ]
    for name, key in (('PelvisDrop', 'pelvis_drop'), ('PelvisToward', 'pelvis_toward'), ('Lean', 'lean'),
                      ('SlideLean', 'slide_lean'), ('SwayTilt', 'sway_tilt'), ('SwayShift', 'sway_shift')):
        lines.append('    internal const float %s = %s;' % (name, f(body[key])))
    for name, key in (('ElbowOut', 'elbow_out'), ('ElbowSide', 'elbow_side'), ('ElbowDown', 'elbow_down'),
                      ('KneeToward', 'knee_toward'), ('KneeSide', 'knee_side'), ('KneeDown', 'knee_down')):
        lines.append('    internal const float %s = %s;' % (name, f(hints[key])))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    with open(JSON, 'rb') as handle:
        raw = handle.read()
    data = json.loads(raw.decode('utf-8'))
    text = render(data, hashlib.sha256(raw).hexdigest())
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current.replace('\r\n', '\n') != text:
            print('GeneratedGait.cs is stale: run compile_gait.py')
            return 1
        print('GeneratedGait.cs matches ladder_gait.json')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)
    print('wrote', OUT)
    return 0


sys.exit(main())
